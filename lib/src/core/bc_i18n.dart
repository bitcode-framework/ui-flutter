// Locale dictionaries are loaded from JSON assets at runtime. The registry
// starts with English only; [registerLocale] adds others. This mirrors the
// TS design where locale JSONs are registered via import side-effects.

/// Framework-agnostic i18n runtime (mirrors TS `BcI18n`).
class BcI18n {
  BcLocale _locale = 'en';
  final Map<String, BcTranslations> _registry = {};

  BcI18n() {
    _registry['en'] = Map.from(_en);
    _registry['id'] = Map.from(_id);
    _registry['fr'] = Map.from(_fr);
    _registry['de'] = Map.from(_de);
    _registry['es'] = Map.from(_es);
    _registry['pt-BR'] = Map.from(_ptBR);
    _registry['ja'] = Map.from(_ja);
    _registry['zh-CN'] = Map.from(_zhCN);
    _registry['ko'] = Map.from(_ko);
    _registry['ar'] = Map.from(_ar);
    _registry['ru'] = Map.from(_ru);
  }

  /// Current locale tag.
  BcLocale get locale => _locale;

  /// Supported locale tags.
  List<BcLocale> get supportedLocales => bcSupportedLocales;

  /// Whether the current locale is RTL.
  bool get isRTL => _rtlLocales.contains(_locale.split('-').first.toLowerCase());

  /// Register (or merge) translations for a locale.
  void registerLocale(BcLocale locale, BcTranslations translations) {
    final existing = _registry[locale] ?? <String, String>{};
    _registry[locale] = {...existing, ...translations};
  }

  /// Set the active locale. Falls back to `en` if unsupported.
  void setLocale(BcLocale locale) {
    if (!bcSupportedLocales.contains(locale)) {
      _locale = 'en';
      return;
    }
    _locale = locale;
  }

  /// Translate a key with optional `{param}` interpolation.
  /// Fallback chain: current locale → `en` → raw key.
  String t(String key, [Map<String, Object?>? params]) {
    final currentDict = _registry[_locale];
    final fallbackDict = _registry['en'];

    var text = currentDict?[key] ?? fallbackDict?[key] ?? key;

    if (params != null) {
      for (final entry in params.entries) {
        text = text.replaceAll('{${entry.key}}', '${entry.value}');
      }
    }
    return text;
  }

  /// Pluralize using simple rule. Looks up `key_one` / `key_other`.
  String plural(String key, int count, [Map<String, Object?>? params]) {
    final rule = count == 1 ? 'one' : 'other';
    final pluralKey = '${key}_$rule';
    final merged = <String, Object?>{'count': count, ...?params};

    final currentDict = _registry[_locale];
    final fallbackDict = _registry['en'];

    if (currentDict?.containsKey(pluralKey) == true ||
        fallbackDict?.containsKey(pluralKey) == true) {
      return t(pluralKey, merged);
    }

    final otherKey = '${key}_other';
    if (currentDict?.containsKey(otherKey) == true ||
        fallbackDict?.containsKey(otherKey) == true) {
      return t(otherKey, merged);
    }

    return t(key, merged);
  }
}

/// Global singleton i18n instance. Synced from [AppConfigStore.setLocale].
final BcI18n bcI18n = BcI18n();
